import { readdirSync, writeFileSync } from "node:fs";
import { basename, extname, join } from "node:path";

const FONT_EXTS = new Set([".ttf", ".otf"]);

const fontsDir = join(process.cwd(), "public", "use-fonts");
const outFile = join(
  process.cwd(),
  "src",
  "lib",
  "fonts",
  "use-fonts.generated.ts",
);

function toFamilyId(fileName: string): string {
  const base = basename(fileName, extname(fileName));
  let slug = base
    .replace(/[^a-zA-Z0-9]+/g, "_")
    .replace(/^_+|_+$/g, "")
    .replace(/_+/g, "_");
  if (!slug) {
    slug = Buffer.from(base, "utf8").toString("hex").slice(0, 16) || "font";
  }
  return `UseFont_${slug}`;
}

function toLabel(fileName: string): string {
  return basename(fileName, extname(fileName))
    .replace(/([a-z])([A-Z])/g, "$1 $2")
    .replace(/-/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

function sortKey(fileName: string): [number, string] {
  const base = basename(fileName, extname(fileName));
  const letterFirst = /^[A-Za-z\u0600-\u06FF]/.test(base) ? 0 : 1;
  return [letterFirst, base.toLowerCase()];
}

const files = readdirSync(fontsDir)
  .filter((name) => FONT_EXTS.has(extname(name).toLowerCase()))
  .sort((a, b) => {
    const [sa, ka] = sortKey(a);
    const [sb, kb] = sortKey(b);
    if (sa !== sb) return sa - sb;
    return ka.localeCompare(kb, "en", { sensitivity: "base" });
  });

const usedFamilies = new Map<string, number>();
const options = files.map((fileName) => {
  let family = toFamilyId(fileName);
  const count = usedFamilies.get(family) ?? 0;
  usedFamilies.set(family, count + 1);
  if (count > 0) family = `${family}_${count + 1}`;

  return {
    family,
    label: toLabel(fileName) || fileName,
    fileName,
    src: `/use-fonts/${encodeURIComponent(fileName)}`,
  };
});

const body = options
  .map(
    (o) =>
      `  {\n    family: ${JSON.stringify(o.family)},\n    label: ${JSON.stringify(o.label)},\n    fileName: ${JSON.stringify(o.fileName)},\n    src: ${JSON.stringify(o.src)},\n  }`,
  )
  .join(",\n");

const content = `/* eslint-disable */
/** Auto-generated by scripts/generate-use-fonts.ts — do not edit by hand. */

export type UseFontGeneratedOption = {
  family: string;
  label: string;
  fileName: string;
  src: string;
};

export const USE_FONT_OPTIONS: UseFontGeneratedOption[] = [
${body}
];
`;

writeFileSync(outFile, content, "utf8");
console.log(`Wrote ${options.length} fonts to ${outFile}`);
